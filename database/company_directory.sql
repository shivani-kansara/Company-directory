DROP DATABASE IF EXISTS company_directory;
CREATE DATABASE company_directory CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE company_directory;

CREATE TABLE location (
  id   INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE department (
  id         INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name       VARCHAR(80) NOT NULL UNIQUE,
  locationID INT UNSIGNED NOT NULL,
  CONSTRAINT fk_department_location FOREIGN KEY (locationID) REFERENCES location(id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE personnel (
  id           INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  firstName    VARCHAR(50)  NOT NULL,
  lastName     VARCHAR(50)  NOT NULL,
  jobTitle     VARCHAR(100) NOT NULL,
  email        VARCHAR(120) NOT NULL UNIQUE,
  phone        VARCHAR(30)  NOT NULL,
  departmentID INT UNSIGNED NOT NULL,
  managerID    INT UNSIGNED NULL,
  INDEX idx_name (lastName, firstName),
  INDEX idx_title (jobTitle),
  CONSTRAINT fk_personnel_department FOREIGN KEY (departmentID) REFERENCES department(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_personnel_manager FOREIGN KEY (managerID) REFERENCES personnel(id)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

